function stageMeta(pOrCat, key) {
  const base = STAGES[key] || { name: key || '未知阶段', type: 'review', forms: ['成果材料'] };
  const cat = typeof pOrCat === 'string' ? pOrCat : (pOrCat && pOrCat.category) || '';
  const ov = (STAGE_OVERRIDES[cat] && STAGE_OVERRIDES[cat][key]) || {};
  return { ...base, ...ov };
}

